"""`hw kb`: the shared knowledge base (field notes by agents, for agents).

Every finished mod — even a failed one — ends as a note, so the next agent
starts where you left off instead of rediscovering the same traps.

Examples:
  hw kb search "grand theft auto"
  hw kb show gta-v/minecraft-passthrough
  hw kb new --game "Hades II" --title "A new boon god" --agent "OpenCode (muse-spark)"
  hw kb check knowledge/games/hades-ii/a-new-boon-god.md
  hw kb index
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

from hw.common import repo_root

STATUSES = {"idea", "in-progress", "working", "released", "abandoned"}
REQUIRED_SECTIONS = ["versions", "route", "verif"]


def kb_root() -> Path:
    return repo_root() / "knowledge"


def all_notes() -> list[Path]:
    root = kb_root()
    if not root.exists():
        return []
    return sorted(p for p in root.rglob("*.md")
                  if p.name not in ("INDEX.md", "README.md", "TEMPLATE.md"))


def search(query: str, limit: int = 10) -> list[tuple[Path, int]]:
    words = [w.lower() for w in re.findall(r"\w+", query)]
    scored = []
    for p in all_notes():
        try:
            text = p.read_text(errors="replace").lower()
        except OSError:
            continue
        score = sum(text.count(w) * (3 if w in p.as_posix().lower() else 1) for w in words)
        if score:
            scored.append((p, score))
    scored.sort(key=lambda t: -t[1])
    return scored[:limit]


def slug(s: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
    return s or "untitled"


def new_note(game: str, title: str, agent: str, kind: str = "game") -> Path:
    root = kb_root()
    if kind == "technique":
        dest = root / "techniques" / f"{slug(title)}.md"
    else:
        dest = root / "games" / slug(game) / f"{slug(title)}.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    if dest.exists():
        from hw.common import fail
        fail(f"note already exists: {dest} — improve it instead of writing a second one")
    tmpl = root / "TEMPLATE.md"
    text = tmpl.read_text() if tmpl.exists() else _fallback_template()
    text = text.replace("<game>", game).replace("<title>", title).replace("<agent>", agent)
    dest.write_text(text)
    return dest


def _fallback_template() -> str:
    return """# <title>

- game: <game>
- status: in-progress
- agents: <agent>
- versions: ...
- route: ...

## What was built
...

## How it was verified
...

## Gotchas
1. symptom → cause → fix
"""


def check_note(path: str | Path) -> list[str]:
    errs = []
    p = Path(path)
    if not p.exists():
        return [f"not found: {p}"]
    text = p.read_text(errors="replace")
    low = text.lower()
    m = re.search(r"status:\s*(\S+)", low)
    if not m or m.group(1).strip("`'\"") not in STATUSES:
        errs.append(f"missing/invalid `status:` (want one of {sorted(STATUSES)})")
    if "agents:" not in low:
        errs.append("missing `agents:` line (name the agent and model)")
    for s in REQUIRED_SECTIONS:
        if s not in low:
            errs.append(f"note never mentions {s!r} (versions, route, verification)")
    for i, block in enumerate(re.findall(r"```.*?```", text, re.S)):
        lines = block.count("\n")
        if lines > 150:
            errs.append(f"code block {i + 1} is {lines} lines — describe logic, don't dump code (>150 fails)")
        elif lines > 60:
            errs.append(f"warn: code block {i + 1} is {lines} lines (keep pasted code short)")
    if re.search(r"sk-[A-Za-z0-9]{20,}|ghp_[A-Za-z0-9]{20,}|BEGIN .*PRIVATE KEY", text):
        errs.append("possible secret in note — remove keys/tokens")
    return [e for e in errs if not e.startswith("warn:")] + \
           [e for e in errs if e.startswith("warn:")]


def rebuild_index() -> Path:
    root = kb_root()
    idx = root / "INDEX.md"
    lines = ["# Knowledge index", "",
             "_Regenerated by `hw kb index`. Field notes by agents, for agents._", ""]
    for p in all_notes():
        try:
            first = p.read_text(errors="replace").splitlines()
        except OSError:
            continue
        title = next((ln.lstrip("# ") for ln in first if ln.startswith("#")), p.stem)
        rel = p.relative_to(root).as_posix()
        lines.append(f"- [{title}]({rel})")
    lines.append("")
    idx.write_text("\n".join(lines))
    data = root / "index.json"
    try:
        import json
        data.write_text(json.dumps([p.relative_to(root).as_posix() for p in all_notes()], indent=2))
    except OSError:
        pass
    return idx


def register(sub):
    p = sub.add_parser("kb", help="knowledge base: search, show, new, check, index, pr")
    sp = p.add_subparsers(dest="cmd", metavar="<cmd>")

    q = sp.add_parser("search", help="search field notes")
    q.add_argument("query")
    q.add_argument("--limit", type=int, default=10)
    q.set_defaults(func=lambda a: _r_search(a))

    q = sp.add_parser("show", help="print a note (path or substring)")
    q.add_argument("note")
    q.set_defaults(func=lambda a: _r_show(a))

    q = sp.add_parser("new", help="scaffold a field note")
    q.add_argument("--game", required=True)
    q.add_argument("--title", required=True)
    q.add_argument("--agent", required=True)
    q.add_argument("--kind", default="game", choices=["game", "technique"])
    q.set_defaults(func=lambda a: print(new_note(a.game, a.title, a.agent, a.kind)))

    q = sp.add_parser("check", help="validate a note")
    q.add_argument("note")
    q.set_defaults(func=lambda a: _r_check(a))

    q = sp.add_parser("index", help="rebuild knowledge/INDEX.md")
    q.set_defaults(func=lambda a: print(f"rebuilt {rebuild_index()}"))

    q = sp.add_parser("pr", help="open a PR with a note (asks first, like everything public)")
    q.add_argument("note")
    q.add_argument("--yes", action="store_true", help="actually run git/gh (else dry run)")
    q.set_defaults(func=lambda a: _r_pr(a))
    p.set_defaults(func=lambda a: p.print_help())


def _r_search(a: argparse.Namespace):
    hits = search(a.query, a.limit)
    if not hits:
        print("(no notes yet — yours will be the first)")
        return
    for p, score in hits:
        try:
            rel = p.relative_to(kb_root()).as_posix()
        except ValueError:
            rel = str(p)
        print(f"{score:>5}  {rel}")


def _r_show(a: argparse.Namespace):
    p = Path(a.note)
    if not p.exists():
        cands = [n for n in all_notes() if a.note.lower() in n.as_posix().lower()]
        if not cands:
            from hw.common import fail
            fail(f"no note matching {a.note!r}")
        p = cands[0]
    print(p.read_text(errors="replace"))


def _r_check(a: argparse.Namespace):
    from hw.common import fail
    errs = check_note(a.note)
    hard = [e for e in errs if not e.startswith("warn:")]
    for e in errs:
        print(("WARN " if e.startswith("warn:") else "FAIL ") + e)
    if hard:
        fail(f"{len(hard)} problem(s) in {a.note}")
    print(f"{a.note}: OK")


def _r_pr(a: argparse.Namespace):
    from hw.common import fail
    cmds = [f"git checkout -b kb/{slug(Path(a.note).stem)}",
            f"git add {a.note} knowledge/INDEX.md knowledge/index.json",
            f"git commit -m 'kb: {Path(a.note).stem}'",
            "git push -u origin HEAD",
            f"gh pr create --title 'kb: {Path(a.note).stem}' --body 'Field note. Tested: see note.'"]
    if not a.yes:
        print("dry run — ask your human first, then re-run with --yes:\n  " + "\n  ".join(cmds))
        return
    for c in cmds:
        r = subprocess.run(c, shell=True)
        if r.returncode != 0:
            fail(f"command failed: {c}")
